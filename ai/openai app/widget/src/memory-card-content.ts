import katex from "katex";

export type MemoryCardContentToken =
  | { type: "text"; value: string }
  | { type: "math"; value: string; display: boolean };

/**
 * Split the small card-markup subset without ever interpreting user HTML.
 * TeX is recognized as `$...$` or `$$...$$`; everything else remains text.
 */
export function tokenizeMemoryCardContent(source: string): MemoryCardContentToken[] {
  const tokens: MemoryCardContentToken[] = [];
  let textStart = 0;
  let cursor = 0;

  while (cursor < source.length) {
    if (source[cursor] !== "$" || isEscaped(source, cursor)) {
      cursor += 1;
      continue;
    }

    const display = source[cursor + 1] === "$";
    const delimiter = display ? "$$" : "$";
    const contentStart = cursor + delimiter.length;
    const closing = findClosingDelimiter(source, contentStart, delimiter);
    if (closing < 0) {
      cursor += delimiter.length;
      continue;
    }

    const expression = source.slice(contentStart, closing).trim();
    if (!expression) {
      cursor = closing + delimiter.length;
      continue;
    }
    if (cursor > textStart) {
      tokens.push({ type: "text", value: source.slice(textStart, cursor) });
    }
    tokens.push({ type: "math", value: expression, display });
    cursor = closing + delimiter.length;
    textStart = cursor;
  }

  if (textStart < source.length) {
    tokens.push({ type: "text", value: source.slice(textStart) });
  }
  if (tokens.length === 0 && source.length > 0) {
    tokens.push({ type: "text", value: source });
  }
  return tokens;
}

/**
 * KaTeX is run with trust disabled and emits MathML, avoiding remote font or
 * stylesheet dependencies inside the sandboxed self-contained widget.
 */
export function renderMemoryCardMath(expression: string, display: boolean): string {
  return katex.renderToString(expression, {
    displayMode: display,
    output: "mathml",
    throwOnError: false,
    strict: "error",
    trust: false
  });
}

export function renderMemoryCardContent(container: HTMLElement, source: string): void {
  container.replaceChildren();
  for (const token of tokenizeMemoryCardContent(source)) {
    if (token.type === "math") {
      const math = document.createElement(token.display ? "div" : "span");
      math.className = token.display ? "math-display" : "math-inline";
      // This markup is generated by KaTeX with trust:false. Learner-authored
      // HTML never reaches this assignment; ordinary text is appended below
      // exclusively through text nodes.
      math.innerHTML = renderMemoryCardMath(token.value, token.display);
      container.append(math);
      continue;
    }
    appendSafeMarkdownText(container, token.value);
  }
}

function appendSafeMarkdownText(container: HTMLElement, value: string): void {
  const lines = value.split("\n");
  lines.forEach((line, index) => {
    appendSafeInlineMarkdown(container, line);
    if (index < lines.length - 1) container.append(document.createElement("br"));
  });
}

/** Bold, emphasis and code are supported without accepting raw HTML. */
function appendSafeInlineMarkdown(container: HTMLElement, value: string): void {
  const pattern = /(\*\*|__)(.+?)\1|(`)(.+?)\3|(\*)([^*]+?)\5|(_)([^_]+?)\7/g;
  let cursor = 0;
  for (const match of value.matchAll(pattern)) {
    const index = match.index ?? 0;
    if (index > cursor) {
      container.append(document.createTextNode(value.slice(cursor, index)));
    }
    const strongText = match[2];
    const codeText = match[4];
    const emphasisText = match[6] ?? match[8];
    const node = document.createElement(
      strongText !== undefined ? "strong" : codeText !== undefined ? "code" : "em"
    );
    node.textContent = strongText ?? codeText ?? emphasisText ?? "";
    container.append(node);
    cursor = index + match[0].length;
  }
  if (cursor < value.length) {
    container.append(document.createTextNode(value.slice(cursor)));
  }
}

function findClosingDelimiter(
  source: string,
  start: number,
  delimiter: "$" | "$$"
): number {
  let cursor = start;
  while (cursor < source.length) {
    const found = source.indexOf(delimiter, cursor);
    if (found < 0) return -1;
    if (!isEscaped(source, found)) return found;
    cursor = found + delimiter.length;
  }
  return -1;
}

function isEscaped(source: string, index: number): boolean {
  let backslashes = 0;
  for (let cursor = index - 1; cursor >= 0 && source[cursor] === "\\"; cursor -= 1) {
    backslashes += 1;
  }
  return backslashes % 2 === 1;
}

