import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, relative, resolve, sep } from 'node:path'
import {
  type GeneratedMarkdownNoticeConfig,
  generatedStatusRegistryReadmeDeNoticeConfig,
  generatedStatusRegistryReadmeNoticeConfig,
  loadGeneratedMarkdownNoticeConfigs,
  loadGeneratedStatusRegistryRows,
  repoRoot,
} from './generatedMarkdownNoticeRegistry'

const outputPath = resolve(repoRoot, generatedStatusRegistryReadmeNoticeConfig.path)
const outputDePath = resolve(repoRoot, generatedStatusRegistryReadmeDeNoticeConfig.path)
const statusDir = resolve(repoRoot, 'docs/qa-ci/status')
const docsRoot = resolve(repoRoot, 'docs')
const checkMode = process.argv.includes('--check')

// Artifacts outside `docs/` are not part of the published MkDocs site, so a
// relative link to them 404s there. Link those through GitHub instead.
const repoBlobPrefix = 'https://github.com/enpasos/skillpilot/blob/main/'

function toPosixPath(path: string): string {
  return path.split(sep).join('/')
}

function isInsideDocs(absolutePath: string): boolean {
  const relativePath = relative(docsRoot, absolutePath)
  return relativePath.length > 0 && !relativePath.startsWith('..')
}

function markdownLink(targetPath: string, fromOutputPath: string): string {
  const absolute = resolve(repoRoot, targetPath)
  const target = isInsideDocs(absolute)
    ? toPosixPath(relative(dirname(fromOutputPath), absolute))
    : `${repoBlobPrefix}${encodeURI(toPosixPath(relative(repoRoot, absolute)))}`
  return `[${basename(targetPath)}](${target})`
}

function joinHumanReadable(items: string[], lang: 'en' | 'de'): string {
  if (items.length === 0) return ''
  if (items.length === 1) return items[0]
  if (lang === 'de') {
    if (items.length === 2) return `${items[0]} und ${items[1]}`
    return `${items.slice(0, -1).join(', ')} und ${items[items.length - 1]}`
  }
  if (items.length === 2) return `${items[0]} and ${items[1]}`
  return `${items.slice(0, -1).join(', ')}, and ${items[items.length - 1]}`
}

function formatArtifactLinks(artifactPaths: string[], fromOutputPath: string, lang: 'en' | 'de'): string {
  return joinHumanReadable(
    artifactPaths.map((artifactPath) => markdownLink(artifactPath, fromOutputPath)),
    lang,
  )
}

function formatCodeItems(items: string[]): string {
  return items.map((item) => `\`${item}\``).join(', ')
}

function listStatusMarkdownPaths(): string[] {
  return readdirSync(statusDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => `docs/qa-ci/status/${entry.name}`)
    .sort((left, right) => left.localeCompare(right, 'en'))
}

function checkRegisteredArtifacts(): string[] {
  const rows = loadGeneratedStatusRegistryRows()
  const registeredArtifacts = [
    generatedStatusRegistryReadmeNoticeConfig.path,
    generatedStatusRegistryReadmeDeNoticeConfig.path,
    ...rows.flatMap((row) => row.artifactPaths),
  ]
  const actualMarkdown = new Set(listStatusMarkdownPaths())
  const registeredMarkdown = new Set(
    loadGeneratedMarkdownNoticeConfigs()
      .map((config) => config.path)
      .filter((path) => path.startsWith('docs/qa-ci/status/') && path.endsWith('.md')),
  )
  const failures: string[] = []

  registeredArtifacts.forEach((artifactPath) => {
    if (!existsSync(resolve(repoRoot, artifactPath))) {
      failures.push(`registered generated status artifact does not exist: ${artifactPath}`)
    }
  })

  Array.from(actualMarkdown).forEach((markdownPath) => {
    if (!registeredMarkdown.has(markdownPath)) {
      failures.push(`unregistered Markdown status artifact: ${markdownPath}`)
    }
  })

  Array.from(registeredMarkdown)
    .sort((left, right) => left.localeCompare(right, 'en'))
    .forEach((markdownPath) => {
      if (!actualMarkdown.has(markdownPath)) {
        failures.push(`registered Markdown status artifact does not exist: ${markdownPath}`)
      }
    })

  return failures
}

function renderGeneratedNotice(noticeConfig: GeneratedMarkdownNoticeConfig): string {
  return [
    '> Generated artifact. Do not edit manually.',
    '>',
    `> Generated by: \`${noticeConfig.generatedBy}\``,
    `> Regenerate with: \`${noticeConfig.regenerateWith}\``,
    ...noticeConfig.sourceOfTruth.map((source) => `> Source of truth: \`${source}\``),
  ].join('\n')
}

function renderRegistry(lang: 'en' | 'de'): string {
  const targetOutputPath = lang === 'de' ? outputDePath : outputPath
  const noticeConfig = lang === 'de'
    ? generatedStatusRegistryReadmeDeNoticeConfig
    : generatedStatusRegistryReadmeNoticeConfig
  const rows = loadGeneratedStatusRegistryRows()
    .map((row) => [
      formatArtifactLinks(row.artifactPaths, targetOutputPath, lang),
      lang === 'de' ? (row.roleDe ?? row.role) : row.role,
      formatCodeItems(row.sourceOfTruth),
      `\`${lang === 'de' ? (row.regenerateWithDe ?? row.regenerateWith) : row.regenerateWith}\``,
    ])

  const tableRows = rows.map((row) => `| ${row.join(' | ')} |`)

  if (lang === 'de') {
    return `${[
      '# Generierte QS-Statusberichte',
      '',
      renderGeneratedNotice(noticeConfig),
      '',
      'Dieses Verzeichnis enthält generierte QS-Berichte, Prüflisten und Dashboard-Momentaufnahmen. Behandle diese Dateien als Laufzeit-Nachweise und nicht als maßgebliche Entscheidungsquelle. Wenn ein Bericht fehlerhaft erscheint, passe das zuständige Skript, die Konfiguration, das Ledger, das Mapping oder die Curriculum-Daten an und erzeuge ihn neu.',
      '',
      '## Regeln',
      '',
      '- Generierte Markdown-, JSON- oder Berichtsdateien niemals manuell bearbeiten.',
      '- Jede generierte Markdown-Datei muss mit dem Herkunftshinweis beginnen, der über `cd app && npm run check:generated-doc-notices` geprüft wird.',
      '- JSON-Begleitdateien sind maschinenlesbare Ausgaben für Werkzeuge und Dashboards; Markdown-Begleitdateien sind menschenlesbare Sichten derselben Prüfspur.',
      '- Jede neue generierte Statusdatei muss in `app/scripts/generatedMarkdownNoticeRegistry.ts` eingetragen werden. Für Markdown-Ausgaben speist derselbe Eintrag die Hinweisprüfung.',
      '- Jede Markdown-Datei direkt unterhalb dieses Verzeichnisses muss in `app/scripts/generatedMarkdownNoticeRegistry.ts` registriert sein.',
      '',
      '## Artefaktverzeichnis',
      '',
      '| Artefakt | Rolle | Maßgebliche Quelle | Neuerzeugung |',
      '| --- | --- | --- | --- |',
      ...tableRows,
      '',
      '## Validierung',
      '',
      'Führe nach Änderungen an generierten Statusdokumenten, ihren Hinweisen oder diesem Verzeichnis folgende Prüfungen aus:',
      '',
      '```bash',
      'cd app',
      'npm run check:generated-doc-notices',
      'npm run check:generated-status-registry',
      'npm run check:docs-links',
      '```',
      '',
      '```bash',
      'git diff --check',
      '```',
      '',
      'Bei Berichten mit zusätzlicher JSON-Begleitdatei ist für nachgelagerte Berichte oder Dashboards stets die JSON-Datei auszuwerten.',
    ].join('\n')}\n`
  }

  return `${[
    '# Generated QA Status Artifacts',
    '',
    renderGeneratedNotice(noticeConfig),
    '',
    'This directory contains generated QA reports, queues, and dashboard snapshots. Treat these files as runtime evidence, not as the decision source. If a report looks wrong, update the owning script, config, ledger, mapping, or curriculum data and regenerate it.',
    '',
    '## Rules',
    '',
    '- Do not edit generated Markdown, JSON, or report output manually.',
    '- Each generated Markdown file must start with the generated-artifact notice checked by `cd app && npm run check:generated-doc-notices`.',
    '- JSON companions are machine-readable outputs for tools and dashboards; Markdown companions are human-readable views of the same lane.',
    '- When adding a new generated status file, add it to `app/scripts/generatedMarkdownNoticeRegistry.ts`. For Markdown outputs, the same entry feeds the notice check.',
    '- Every Markdown file directly under this directory must be registered in `app/scripts/generatedMarkdownNoticeRegistry.ts`.',
    '',
    '## Artifact Registry',
    '',
    '| Artifact | Role | Source of truth | Regenerate |',
    '| --- | --- | --- | --- |',
    ...tableRows,
    '',
    '## Validation',
    '',
    'Use these checks after changing generated status docs, their notices, or this registry:',
    '',
    '```bash',
    'cd app',
    'npm run check:generated-doc-notices',
    'npm run check:generated-status-registry',
    'npm run check:docs-links',
    '```',
    '',
    '```bash',
    'git diff --check',
    '```',
    '',
    'For generated reports that also emit JSON, parse the JSON companion before relying on it in another report or dashboard.',
  ].join('\n')}\n`
}

const rendered = renderRegistry('en')
const renderedDe = renderRegistry('de')

if (checkMode) {
  const failures = checkRegisteredArtifacts()
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : ''
  if (current !== rendered) {
    failures.push(`${generatedStatusRegistryReadmeNoticeConfig.path} is stale. Regenerate it with: ${generatedStatusRegistryReadmeNoticeConfig.regenerateWith}`)
  }
  const currentDe = existsSync(outputDePath) ? readFileSync(outputDePath, 'utf8') : ''
  if (currentDe !== renderedDe) {
    failures.push(`${generatedStatusRegistryReadmeDeNoticeConfig.path} is stale. Regenerate it with: ${generatedStatusRegistryReadmeDeNoticeConfig.regenerateWith}`)
  }
  if (failures.length > 0) {
    console.error(failures.join('\n'))
    process.exit(1)
  }
  console.log(`${generatedStatusRegistryReadmeNoticeConfig.path} and ${generatedStatusRegistryReadmeDeNoticeConfig.path} are up to date.`)
} else {
  writeFileSync(outputPath, rendered)
  writeFileSync(outputDePath, renderedDe)
  console.log(`Wrote ${generatedStatusRegistryReadmeNoticeConfig.path}`)
  console.log(`Wrote ${generatedStatusRegistryReadmeDeNoticeConfig.path}`)
}
