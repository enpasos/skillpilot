package com.skillpilot.backend.claude.mcp;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.skillpilot.backend.actionregression.ActionRegressionAuditLogger;
import com.skillpilot.backend.actionregression.ActionRegressionService;
import org.springframework.ai.tool.annotation.Tool;
import org.springframework.ai.tool.annotation.ToolParam;

/**
 * Privacy-safe tools for verifying MCP result handoff and cross-turn chaining.
 *
 * <p>The generated values are random regression markers. They are not learner,
 * account or authentication data.</p>
 */
public final class ActionRegressionMcpTools {

    private final ActionRegressionService regressionService;
    private final ActionRegressionAuditLogger auditLogger;

    ActionRegressionMcpTools(
            ActionRegressionService regressionService,
            ActionRegressionAuditLogger auditLogger) {
        this.regressionService = regressionService;
        this.auditLogger = auditLogger;
    }

    @Tool(
            name = "createRegressionProbe",
            description = "Create an inert synthetic sample for an MCP handoff regression test. "
                    + "This operation reads or writes no learner or account data and performs no authorization action.")
    public RegressionProbe createRegressionProbe() {
        ActionRegressionService.Probe probe = regressionService.issueProbe();
        auditLogger.logClaudeMcpProbeIssued(probe.probeId(), probe.token(), probe.proof());
        return new RegressionProbe(probe.probeId(), probe.token(), probe.proof());
    }

    @Tool(
            name = "verifyRegressionProbe",
            description = "Check whether inert synthetic sample data from createRegressionProbe was transferred "
                    + "unchanged. This operation reads or writes no learner or account data and performs no "
                    + "authorization action.")
    public RegressionVerification verifyRegressionProbe(
            // The Java name intentionally matches the JSON wire field generated by Spring AI.
            @ToolParam(description = "Identifier of the synthetic sample") String probe_id,
            @ToolParam(description = "Random marker belonging to the synthetic sample") String sample_marker,
            @ToolParam(description = "Integrity tag belonging to the synthetic sample") String integrity_tag) {
        boolean valid = regressionService.verifyProbe(probe_id, sample_marker, integrity_tag);
        auditLogger.logClaudeMcpProbeVerified(probe_id, sample_marker, integrity_tag, valid);
        return new RegressionVerification(valid, probe_id, valid);
    }

    public record RegressionProbe(
            @JsonProperty("probe_id") String probeId,
            @JsonProperty("sample_marker") String sampleMarker,
            @JsonProperty("integrity_tag") String integrityTag) {
    }

    public record RegressionVerification(
            boolean ok,
            @JsonProperty("probe_id") String probeId,
            @JsonProperty("integrity_valid") boolean integrityValid) {
    }
}
